// ── Student hooks ──────────────────────────────────────────────────────────────
export function usePublishedQuestions(topicId: number | null) {
  return useQuery({
    queryKey: QK.published(topicId!),
    queryFn: () => questionApi.listPublished(topicId!),
    enabled: !!topicId,
  });
}
