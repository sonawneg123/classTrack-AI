// src/features/questions/hooks/useQuestions.ts

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useSnackbar } from "notistack";
import { questionApi } from "../api/questionApi";
import { getErrorMessage } from "@utils/apiError";
import type { GenerateQuestionsRequest, QuestionStatus } from "@/types/question";

// ── Query keys ────────────────────────────────────────────────────────────────
const QK = {
  pendingApproval: ["questions", "pending-approval"] as const,
  byTopic: (topicId: number, status?: QuestionStatus) =>
    ["questions", "topic", topicId, status ?? "all"] as const,
  myQuestions: (topicId?: number) =>
    ["questions", "my-questions", topicId ?? "all"] as const,
  published: (topicId: number) => ["questions", "published", topicId] as const,
  single: (id: number) => ["questions", id] as const,
};

// ── Generation ─────────────────────────────────────────────────────────────────
export function useGenerateQuestions() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (payload: GenerateQuestionsRequest) => questionApi.generate(payload),
    onSuccess: (data, vars) => {
      // Invalidate the student's "my questions" view so newly generated
      // questions appear immediately from the database (not from mutation state).
      qc.invalidateQueries({ queryKey: QK.myQuestions() });
      qc.invalidateQueries({ queryKey: QK.myQuestions(vars.topicId) });
      qc.invalidateQueries({ queryKey: QK.byTopic(vars.topicId) });
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      enqueueSnackbar(
        `${data.stored} question(s) generated and pending approval.`,
        { variant: "success" }
      );
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

// ── Student: my generated questions ────────────────────────────────────────────
/**
 * Fetches all questions generated by the current student (all statuses).
 * Polls every 15 seconds so status changes made by the teacher propagate
 * to the student UI without a manual page refresh.
 * No WebSockets or SSE required — simple polling is appropriate here since
 * the latency requirement is "within a reasonable time" not "sub-second".
 */
export function useMyQuestions(topicId?: number) {
  return useQuery({
    queryKey: QK.myQuestions(topicId),
    queryFn: () => questionApi.listMyQuestions(topicId),
    // Poll every 15 s while the page is open and the window is focused.
    refetchInterval: 15_000,
    // Also refetch when the browser tab regains focus (student switches back
    // from the teacher tab after approving).
    refetchOnWindowFocus: true,
  });
}

// ── Teacher hooks ──────────────────────────────────────────────────────────────
export function useQuestionsByTopic(topicId: number | null, status?: QuestionStatus) {
  return useQuery({
    queryKey: QK.byTopic(topicId!, status),
    queryFn: () => questionApi.listByTopic(topicId!, status),
    enabled: !!topicId,
  });
}

export function usePendingApproval() {
  return useQuery({
    queryKey: QK.pendingApproval,
    queryFn: () => questionApi.listPendingApproval(),
  });
}

export function useApproveQuestion() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (id: number) => questionApi.approve(id),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      enqueueSnackbar("Question approved.", { variant: "success" });
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

export function useRejectQuestion() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: ({ id, reason }: { id: number; reason?: string }) =>
      questionApi.reject(id, reason),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      enqueueSnackbar("Question rejected.", { variant: "warning" });
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

