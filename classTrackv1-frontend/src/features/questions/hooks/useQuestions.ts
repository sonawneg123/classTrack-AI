export function useApproveQuestion() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (id: number) => questionApi.approve(id),
    onSuccess: () => {
      // After approving, question moves from pending_approval → approved
      // Invalidate both the review queue and legacy pending-approval
      qc.invalidateQueries({ queryKey: QK.reviewQueue() });
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      enqueueSnackbar("Question approved.", { variant: "success" });
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

export function useRejectQuestion() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: ({ id, reason }: { id: number; reason?: string }) =>
      questionApi.reject(id, reason),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: QK.reviewQueue() });
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      enqueueSnackbar("Question rejected.", { variant: "warning" });
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

export function usePublishQuestion() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (id: number) => questionApi.publish(id),
    onSuccess: () => {
      // After publishing, question leaves review queue and enters published pool
      // Must invalidate: review queue, legacy pending, published teacher list,
      // AND all topic-based published-count queries used by the Quiz Builder
      qc.invalidateQueries({ queryKey: QK.reviewQueue() });
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      qc.invalidateQueries({ queryKey: QK.publishedTeacher() });
      // Invalidate all topic-based published queries (used by quiz builder SourceCard)
      qc.invalidateQueries({ queryKey: ["questions", "topic"] });
      // Invalidate all published-count queries in the quiz assignments feature
      qc.invalidateQueries({ queryKey: ["questions"] });
      enqueueSnackbar("Question published. It is now available in the Quiz Builder.", { variant: "success" });
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

export function useArchiveQuestion() {
  const { enqueueSnackbar } = useSnackbar();
  const qc = useQueryClient();
  return useMutation({
    mutationFn: ({ id }: { id: number }) => questionApi.archive(id),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: QK.reviewQueue() });
      qc.invalidateQueries({ queryKey: QK.pendingApproval });
      qc.invalidateQueries({ queryKey: QK.publishedTeacher() });
      qc.invalidateQueries({ queryKey: ["questions"] });
      enqueueSnackbar("Question archived.", { variant: "info" });
    },
    onError: (e) => enqueueSnackbar(getErrorMessage(e), { variant: "error" }),
  });
}

