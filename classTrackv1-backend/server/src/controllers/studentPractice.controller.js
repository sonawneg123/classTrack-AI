/**
 * server/src/controllers/studentPractice.controller.js
 *
 * HTTP handlers for the Student AI Practice API.
 *
 * All endpoints are student-only and require question:practice_generate permission.
 * Business logic delegated to studentPractice.service — no SQL here.
 */
const { ApiResponse, asyncHandler } = require('../utils/response.util');
const practiceService = require('../services/questions/studentPractice.service');

// ── Generate practice questions ───────────────────────────────────────────────

/**
 * POST /api/v1/practice/generate
 *
 * Student generates AI practice questions for a topic.
 * Questions are stored as status='practice' — invisible to teachers.
 *
 * Body: { topicId, questionType, difficulty, count }
 */
const generatePractice = asyncHandler(async (req, res) => {
  const { topicId, questionType, difficulty, count } = req.body;
  const studentId = req.user.id;
  // Pass the request ID (set by requestId.middleware.js) for RAG observability
  const requestId = req.id || req.headers['x-request-id'];

  const result = await practiceService.generatePracticeQuestions({
    studentId,
    topicId,
    questionType,
    difficulty,
    count,
    requestId,
  });

  // INSUFFICIENT_CONTEXT — surface structured error to frontend
  if (result.insufficientContext) {
    return new ApiResponse(200, result.message, {
      code:                'INSUFFICIENT_CONTEXT',
      insufficientContext: true,
      generated:           0,
      stored:              0,
      questions:           [],
    }).send(res);
  }

  new ApiResponse(201, `${result.stored} practice question(s) generated.`, result).send(res);
});

// ── List practice questions ───────────────────────────────────────────────────

/**
 * GET /api/v1/practice/questions
 * Optional query: ?topicId=<number>
 *
 * Returns all practice questions generated by this student (optionally
 * filtered by topic).
 */
const listPracticeQuestions = asyncHandler(async (req, res) => {
  const { topicId } = req.query;
  const opts = topicId ? { topicId: Number(topicId) } : {};
  const questions = await practiceService.listPracticeQuestions(req.user.id, opts);
  new ApiResponse(200, 'Practice questions retrieved.', { questions }).send(res);
});

/**
 * GET /api/v1/practice/questions/:questionId
 * Get a single practice question owned by this student.
 */
const getPracticeQuestion = asyncHandler(async (req, res) => {
  const data = await practiceService.getPracticeQuestion(
    Number(req.params.questionId),
    req.user.id
  );
  new ApiResponse(200, 'Practice question retrieved.', data).send(res);
});

// ── Practice attempts ─────────────────────────────────────────────────────────

/**
 * POST /api/v1/practice/questions/:questionId/attempt
 * Student submits an answer to one of their own practice questions.
 *
 * Body: { studentAnswer: string }
 */
const submitPracticeAttempt = asyncHandler(async (req, res) => {
  const data = await practiceService.submitPracticeAttempt(
    Number(req.params.questionId),
    req.user.id,
    req.body.studentAnswer
  );
  new ApiResponse(201, 'Answer submitted.', data).send(res);
});

/**
 * GET /api/v1/practice/questions/:questionId/attempt
 * Get the student's own attempt for one practice question (null if not yet attempted).
 */
const getPracticeAttempt = asyncHandler(async (req, res) => {
  const data = await practiceService.getPracticeAttempt(
    Number(req.params.questionId),
    req.user.id
  );
  new ApiResponse(200, 'Attempt retrieved.', data ?? null).send(res);
});

module.exports = {
  generatePractice,
  listPracticeQuestions,
  getPracticeQuestion,
  submitPracticeAttempt,
  getPracticeAttempt,
};
